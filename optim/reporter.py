# ── Report Generator ───────────────────────────────────────────────────────────


def generate_json_report(report: OptimReport) -> str:
    """Generate a JSON string from the report."""
    return json.dumps(report.to_dict(), indent=2, ensure_ascii=False)


def generate_markdown_report(report: OptimReport) -> str:
    """Generate a human-readable Markdown string from the report."""
    round_details_parts: list[str] = []

    for rnd in report.rounds:
        icon = "✅" if rnd.converged else "⚙️"
        model_count = len(rnd.model_changes)

        # Build model changes section if any
        model_section = ""
        if rnd.model_changes:
            lines = ["\n**Model Routing Changes**:\n"]
            for mc in rnd.model_changes:
                action = mc.get("action", "unknown")
                model = mc.get("model", "?")
                reason = mc.get("reason", "")
                emoji = {"keep": "✅", "demote": "⚠️", "remove": "❌"}.get(action, "➖")
                lines.append(f"- {emoji} **{model}** → `{action}`: {reason}")
            model_section = "\n".join(lines)

        analysis_lines: list[str] = []
        for tuning in rnd.tuning_results:
            agent = tuning.get("agent", "?")
            score = tuning.get("best_score", 0.0)
            analysis_lines.append(f"- Tuned **{agent}**: best score {score:.4f}")

        analysis = "\n".join(analysis_lines) if analysis_lines else "No tunings."

        round_details_parts.append(
            ROUND_TEMPLATE.format(
                num=rnd.round_num,
                converged_icon=icon,
                mean=rnd.mean_score,
                median=rnd.median_score,
                cost=rnd.total_cost_usd,
                evals=len(rnd.eval_results),
                models=model_count,
                converged="Yes" if rnd.converged else "No",
                analysis=analysis,
                model_changes_section=model_section,
            )
        )

    # Collect recommendations from analyser
    recs_raw: list[str] = []
    for rnd in report.rounds:
        for tuning in rnd.tuning_results:
            recs_raw.append(f"- Keep tuned prompt for **{tuning.get('agent', '?')}**")
        for mc in rnd.model_changes:
            if mc.get("action") in ("demote", "remove"):
                recs_raw.append(
                    f"- Consider replacing **{mc.get('model', '?')}** — "
                    f"success rate {mc.get('success_rate', 0):.2f}"
                )
    recommendations = "\n".join(dict.fromkeys(recs_raw)) if recs_raw else "- Continue monitoring."

    return MARKDOWN_TEMPLATE.format(
        supervisor_id=report.supervisor_id,
        status=report.status,
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        total_rounds=len(report.rounds),
        best_score=report.best_score,
        best_round=report.best_round,
        total_cost=report.total_cost_usd,
        total_evals=report.total_evaluations,
        total_tunings=report.total_tunings,
        started_at=report.started_at,
        finished_at=report.finished_at or "In progress",
        round_details="\n\n".join(round_details_parts),
        recommendations=recommendations,
    )


# ── File Output ────────────────────────────────────────────────────────────────


def write_reports(
    report: OptimReport,
    output_dir: str | Path = "reports",
    *,
    formats: list[str] | None = None,
) -> dict[str, Path]:
    """Write report files to disk.

    Args:
        report: The completed OptimReport.
        output_dir: Directory to write into.
        formats: Which formats to output ("json", "markdown", or both).

    Returns:
        Dict mapping format → output file Path.
    """
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    fmts = formats or ["json", "markdown"]
    written: dict[str, Path] = {}

    session_id = report.supervisor_id.replace(" ", "_").replace(":", "-")
    base_name = f"phase5_report_{session_id}"

    if "json" in fmts:
        json_file = output_path / f"{base_name}.json"
        json_file.write_text(generate_json_report(report), encoding="utf-8")
        written["json"] = json_file
        logger.info("JSON report written: %s", json_file)

    if "markdown" in fmts:
        md_file = output_path / f"{base_name}.md"
        md_file.write_text(generate_markdown_report(report), encoding="utf-8")
        written["markdown"] = md_file
        logger.info("Markdown report written: %s", md_file)

    return written


# ── Test Compatibility Classes ───────────────────────────────────────────────────


@dataclass
class ReporterConfig:
    """Configuration for report generation."""

    output_dir: str = "reports"
    formats: list[str] = None

    def __post_init__(self):
        if self.formats is None:
            self.formats = ["json", "markdown"]


class OptimisationReporter:
    """Reporter class for generating optimisation reports."""

    def __init__(self, config: ReporterConfig | None = None) -> None:
        self.config = config or ReporterConfig()

    def generate(
        self,
        report: OptimReport,
        output_dir: str | Path | None = None,
        formats: list[str] | None = None,
    ) -> dict[str, Path]:
        """Generate reports in specified formats."""
        return write_reports(
            report,
            output_dir or self.config.output_dir,
            formats=formats or self.config.formats,
        )


def generate_report(
    report: OptimReport,
    output_dir: str | Path = "reports",
    formats: list[str] | None = None,
) -> dict[str, Path]:
    """Convenience function to generate reports."""
    return write_reports(report, output_dir, formats=formats)
